export const villagesOrder = ['Kahyapu', 'Kaana', 'Meok', 'Apoho', 'Malakoni', 'Banjarsari']

export const villagesList = villagesOrder.map((name) => villageProfiles[name])

export function findVillageByName(name) {
  return villageProfiles[name] || null
}

export function findVillageBySlug(slug) {
  return villagesList.find((v) => v.slug === slug) || null
}

export function getVillagePrevNext(slug) {
  const idx = villagesList.findIndex((v) => v.slug === slug)
  if (idx === -1) return { prev: null, next: null }
  return {
    prev: idx > 0 ? villagesList[idx - 1] : null,
    next: idx < villagesList.length - 1 ? villagesList[idx + 1] : null,
  }
}

export const villageMapMarkers = villagesList
  .filter((v) => v.lat != null && v.lng != null)
  .map((v) => ({
    name: v.name,
    lat: v.lat,
    lng: v.lng,
    slug: v.slug,
  }))

